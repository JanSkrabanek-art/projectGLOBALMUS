document.addEventListener('keydown', (event) => {
  if (event.key === 'Escape' && menuToggle.getAttribute('aria-expanded') === 'true') {
    closeMenu();
    menuToggle.focus();
  }
});

function openLightbox(groupName, index) {
  if (!galleryGroups[groupName]) {
    console.error(`Missing photo gallery: ${groupName}`);
    return;
  }
  activeGalleryGroup = groupName;
  activeGalleryIndex = index;
  renderLightbox();
  lightbox.showModal();
  document.querySelector('[data-lightbox-close]').focus();
}

function stepLightbox(direction) {
  const gallery = galleryGroups[activeGalleryGroup].items;
  activeGalleryIndex = (activeGalleryIndex + direction + gallery.length) % gallery.length;
  renderLightbox();
}

document.querySelector('#main').addEventListener('click', (event) => {
  const item = event.target.closest('[data-gallery-index]');
  if (item) openLightbox(item.dataset.galleryGroup, Number(item.dataset.galleryIndex));
});

document.querySelector('[data-lightbox-close]').addEventListener('click', () => lightbox.close());
document.querySelector('[data-lightbox-prev]').addEventListener('click', () => stepLightbox(-1));
document.querySelector('[data-lightbox-next]').addEventListener('click', () => stepLightbox(1));
lightbox.addEventListener('click', (event) => {
  if (event.target === lightbox) lightbox.close();
});
lightbox.addEventListener('keydown', (event) => {
  if (event.key === 'ArrowLeft') stepLightbox(-1);
  if (event.key === 'ArrowRight') stepLightbox(1);
  if (event.key === 'Escape') {
    event.preventDefault();
    lightbox.close();
  }
});

