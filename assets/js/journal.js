let language = readSavedLanguage();
let activeGalleryIndex = 0;
let activeGalleryGroup = 'journal';

function readSavedLanguage() {
  try {
    return localStorage.getItem('journal-language') === 'en' ? 'en' : 'cs';
  } catch {
    return 'cs';
  }
}

function translate(key) {
  const value = translations[language][key];
  if (!value) console.error(`Missing ${language} translation: ${key}`);
  return value || '';
}

function translatedField(value) {
  if (!value || typeof value !== 'object') return '';
  const translatedValue = value[language];
  if (!translatedValue) console.error(`Missing ${language} field translation`);
  return translatedValue || '';
}

function applyTranslations() {
  document.documentElement.lang = language;
  document.title = translate('meta.title');
  document.querySelector('meta[name="description"]').content = translate('meta.description');
  document.querySelector('meta[property="og:title"]').content = document.title;
  document.querySelector('meta[property="og:description"]').content = translate('meta.description');

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    element.textContent = translate(element.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-aria]').forEach((element) => {
    element.setAttribute('aria-label', translate(element.dataset.i18nAria));
  });
  document.querySelectorAll('[data-i18n-alt]').forEach((element) => {
    element.alt = translate(element.dataset.i18nAlt);
  });
  languageButtons.forEach((button) => {
    button.setAttribute('aria-pressed', String(button.dataset.language === language));
  });
  document.querySelectorAll('.wordmark').forEach((wordmark) => {
    wordmark.setAttribute('aria-label', language === 'cs' ? 'Jan Škrabánek, úvod' : 'Jan Škrabánek, home');
  });
  document.querySelector('#gallery-grid').setAttribute('aria-label', language === 'cs' ? 'Fotogalerie' : 'Photo gallery');
  document.querySelector('#lightbox').setAttribute('aria-label', language === 'cs' ? 'Fotogalerie' : 'Photo gallery');
  document.querySelector('#current-year').textContent = String(new Date().getFullYear());
}

function galleryCaption(item) {
  return item.captionKey ? translate(item.captionKey) : translatedField(item.caption);
}

function renderGallery() {
  document.querySelectorAll('[data-gallery]').forEach((grid) => {
    const groupName = grid.dataset.gallery;
    const group = galleryGroups[groupName];
    if (!group) {
      console.error(`Missing photo gallery: ${groupName}`);
      return;
    }

    grid.replaceChildren();
    group.items.forEach((item, index) => {
      const button = document.createElement('button');
      button.className = 'gallery-item';
      button.type = 'button';
      button.dataset.galleryGroup = groupName;
      button.dataset.galleryIndex = String(index);
      button.setAttribute('aria-label', `${galleryCaption(item)}. ${language === 'cs' ? 'Otevřít fotografii' : 'Open photograph'}`);
      const image = document.createElement('img');
      image.src = item.image;
      image.alt = translatedField(item.alt);
      image.loading = 'lazy';
      image.decoding = 'async';
      const caption = document.createElement('span');
      caption.className = 'gallery-item__caption';
      const text = document.createElement('span');
      text.textContent = galleryCaption(item);
      const tag = document.createElement('span');
      tag.textContent = translate(group.context);
      caption.append(text, tag);
      button.append(image, caption);
      grid.append(button);
    });
  });
}

function renderLightbox() {
  const group = galleryGroups[activeGalleryGroup];
  const item = group?.items[activeGalleryIndex];
  if (!item) return;
  const image = document.querySelector('#lightbox-image');
  image.src = item.image;
  image.alt = translatedField(item.alt);
  document.querySelector('#lightbox-caption').textContent = `${galleryCaption(item)} · ${translate(group.context)}`;
}

function setLanguage(nextLanguage) {
  if (!translations[nextLanguage] || nextLanguage === language) return;
  const activeSection = [...document.querySelectorAll('main section[id]')].find((section) => {
    const bounds = section.getBoundingClientRect();
    return bounds.bottom > 88 && bounds.top < window.innerHeight;
  });
  const sectionTop = activeSection?.getBoundingClientRect().top;
  language = nextLanguage;
  try {
    localStorage.setItem('journal-language', language);
  } catch {
    // Language switching remains available when storage is disabled.
  }
  applyTranslations();
  renderGallery();
  if (lightbox.open) renderLightbox();
  if (activeSection && sectionTop !== undefined) {
    const topDelta = activeSection.getBoundingClientRect().top - sectionTop;
    window.scrollTo({ top: window.scrollY + topDelta, behavior: 'instant' });
  }
}

function closeMenu() {
  menuToggle.setAttribute('aria-expanded', 'false');
  menuToggle.setAttribute('aria-label', translate('menu.open'));
  primaryNav.classList.remove('is-open');
}

function showPortraitFallback() {
  portraitImage.closest('.portrait-slot').classList.add('portrait-slot--missing');
}

